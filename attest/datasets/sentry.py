"""SENTRY access events with breach incidents as labels.

SENTRY's compliance engine already stores the two things a real evaluation
needs: ``access_events`` is a per-principal event stream with timestamps, and
``breach_incidents`` records when a principal was judged to be in breach. That
makes it the first corpus available to this project that is neither generated
here nor gated behind an access request.

What the labels actually are
----------------------------
``breach_incidents`` rows are produced by SENTRY's own rule-based detector, not
by a red team and not by an incident responder confirming a real compromise.
They are **weak supervision**: a strong signal that something crossed a
threshold, not ground truth that an account was under attacker control.

That has a specific consequence worth stating before anyone reads a number off
this. If a policy is scored against labels generated by a threshold rule, then
a policy that behaves like that threshold rule will look good, and any policy
that fires earlier - which is exactly what integrating evidence over time is
meant to do - will be counted as wrong for firing before the rule did. Exposure
measured this way is bounded below by the detector's own latency.

So this corpus is useful for two things: checking that the pipeline behaves
sensibly on real telemetry, and comparing policies against each other. It is
not evidence that the scheduler catches real compromise, and a result from it
should never be reported as though it were. That claim still needs a corpus
with adversary-generated ground truth.
"""

from __future__ import annotations

from dataclasses import dataclass

from ..learn import RollingFeatures
from .base import Timeline
from .sql import Connection, rows, to_epoch

__all__ = ["SentryConfig", "load"]

name = "sentry"


@dataclass(frozen=True)
class SentryConfig:
    """Loader settings.

    Args:
        tenant_id: Restrict to one tenant. None reads every tenant, which mixes
            populations with different baselines and is rarely what you want.
        min_events: Principals with fewer events than this are dropped. A
            handful of events is not a timeline, and the warm-up window means
            their features are mostly noise.
        max_events_per_entity: Cap per principal, oldest kept.
        episode_pad: Seconds either side of an incident that count as part of
            the compromise window. The detector fires *after* the behaviour it
            is reacting to, so a window anchored only at ``detected_at`` would
            label the aftermath and miss the event that caused it.
        breadth_window: Window for counting distinct resources touched.
        warmup: Events before novelty signals count fully.
    """

    tenant_id: str | None = None
    min_events: int = 30
    max_events_per_entity: int = 4000
    episode_pad: float = 900.0
    breadth_window: float = 3600.0
    warmup: int = 50


def load(
    connection: Connection, config: SentryConfig | None = None
) -> list[Timeline]:
    """Read access events and breach incidents into per-principal timelines.

    Args:
        connection: Any DB-API connection to a SENTRY database.
        config: Loader settings.

    Returns:
        One timeline per retained principal, time-ordered.
    """
    cfg = config or SentryConfig()

    incident_sql = "SELECT principal, detected_at FROM breach_incidents"
    event_sql = (
        "SELECT principal, occurred_at, action, resource, records_touched, "
        "bytes_out, source_ip, succeeded FROM access_events"
    )
    params: tuple = ()
    if cfg.tenant_id is not None:
        incident_sql += " WHERE tenant_id = ?"
        event_sql += " WHERE tenant_id = ?"
        params = (cfg.tenant_id,)
    event_sql += " ORDER BY occurred_at"

    windows: dict[str, list[tuple[float, float]]] = {}
    for row in rows(connection, incident_sql, params):
        principal = row["principal"]
        if not principal:
            continue
        at = to_epoch(row["detected_at"])
        windows.setdefault(principal, []).append(
            (at - cfg.episode_pad, at + cfg.episode_pad)
        )
    for spans in windows.values():
        spans.sort()

    grouped: dict[str, list[dict]] = {}
    for row in rows(connection, event_sql, params):
        principal = row["principal"]
        if not principal:
            continue
        bucket = grouped.setdefault(principal, [])
        if len(bucket) < cfg.max_events_per_entity:
            bucket.append(row)

    timelines: list[Timeline] = []
    for principal, events in grouped.items():
        if len(events) < cfg.min_events:
            continue

        rolling = RollingFeatures(
            breadth_window=cfg.breadth_window, warmup=cfg.warmup
        )
        times, features, is_attack, episode = [], [], [], []

        for row in events:
            at = to_epoch(row["occurred_at"])
            action = row.get("action") or "unknown"
            resource = row.get("resource") or ""

            feature = rolling.observe(
                at,
                {
                    "action": action,
                    "resource": resource,
                    "source_ip": row.get("source_ip") or "",
                },
                peer=resource,
            )
            feature["failed"] = 0.0 if row.get("succeeded", 1) else 1.0
            feature["login_failed"] = 1.0 if action == "login_failed" else 0.0
            feature["export"] = 1.0 if action == "export" else 0.0
            # Volume is the DPDPA signal: a bulk export is what an exfiltration
            # looks like from the data layer. Log-scaled so one large transfer
            # does not swamp every other feature.
            feature["records"] = _log1p(row.get("records_touched") or 0)
            feature["bytes_out"] = _log1p(row.get("bytes_out") or 0)

            span = _window_for(windows.get(principal), at)
            times.append(at)
            features.append(feature)
            is_attack.append(span is not None)
            episode.append(f"{principal}@{span[0]:.0f}" if span else None)

        timelines.append(
            Timeline(
                entity_id=principal,
                times=times,
                features=features,
                is_attack=is_attack,
                episode=episode,
            )
        )

    return timelines


def _log1p(value) -> float:
    import math

    try:
        return math.log1p(max(0.0, float(value)))
    except (TypeError, ValueError):
        return 0.0


def _window_for(
    spans: list[tuple[float, float]] | None, at: float
) -> tuple[float, float] | None:
    if not spans:
        return None
    for start, end in spans:
        if start <= at <= end:
            return (start, end)
    return None
